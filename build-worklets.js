//@ts-check
/**
 * Pre-builds the AudioWorkletProcessor modules as strings.
 *
 * A Faust AudioWorklet node needs its processor code inside the
 * AudioWorkletGlobalScope, which only takes a module URL. That code used to be
 * assembled at run time from `Class.toString()` and `Class.name`, which breaks
 * as soon as the application embedding this package minifies it: the
 * minifier renames the identifiers the class bodies use to refer to one
 * another, independently of `.name`, and the worklet module ends up with free
 * references (grame-cncm/faustwasm#53).
 *
 * Here each processor is bundled once, at this package's build time, into a
 * self-contained IIFE whose internal references esbuild resolves itself. The
 * result is written as string constants to `src/generated/workletSources.ts`
 * (gitignored), which the generator imports. A string literal is opaque to a
 * downstream minifier, so the module survives whatever bundler comes next.
 *
 * The only free identifiers left in each source are the worklet globals and
 * the ones the generator prepends at run time: `faustData`, and `FFTUtils` for
 * the FFT processor.
 *
 * Every build script runs this first, some of them in parallel, so the file is
 * written atomically and only when its content changes.
 */
import * as esbuild from 'esbuild';
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/** Exported constant name -> worklet entry point. */
const ENTRIES = {
    monoProcessorSource: 'src/worklet/monoProcessor.ts',
    polyProcessorSource: 'src/worklet/polyProcessor.ts',
    fftProcessorSource: 'src/worklet/fftProcessor.ts'
};

const outFile = path.join(__dirname, 'src/generated/workletSources.ts');

let content =
    '// Generated by build-worklets.js from src/worklet/*.ts. Do not edit.\n';
for (const [name, entry] of Object.entries(ENTRIES)) {
    const result = await esbuild.build({
        entryPoints: [path.join(__dirname, entry)],
        bundle: true,
        write: false,
        format: 'iife',
        target: 'es2019',
        platform: 'browser',
        // Each source is a closed world, so renaming inside it is safe, and
        // it keeps the three strings (which every dist bundle carries on top
        // of the main-thread code) at about 45% of their size. Names are
        // kept so a stack trace in the worklet console still reads.
        minify: true,
        keepNames: true,
        logLevel: 'warning'
    });
    const source = result.outputFiles[0].text;
    content += `export const ${name} = ${JSON.stringify(source)};\n`;
}

const previous = fs.existsSync(outFile)
    ? fs.readFileSync(outFile, 'utf8')
    : null;
if (previous !== content) {
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    const tmp = `${outFile}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, outFile);
}
